pub fn t(key: &'static str, locale: Locale) -> &'static str {
    match locale {
        Locale::En => key,
        Locale::ZhCn => zh_cn().get(key).copied().unwrap_or(key),
    }
}

pub fn t_string(key: &str, locale: Locale) -> String {
    match locale {
        Locale::En => key.to_string(),
        Locale::ZhCn => zh_cn()
            .get(key)
            .map(|s| s.to_string())
            .unwrap_or_else(|| key.to_string()),
    }
}

